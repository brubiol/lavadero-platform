-- Mexican + US (border-traffic) holidays that influence car-wash demand in Reynosa.
-- Seeded for 2025-2027. Future years should be added by a follow-up migration.
--
-- country = 'MX' (Mexican holiday), 'US' (US holiday), 'BOTH' (calendar dates both observe).
-- drives_border_traffic = true means the holiday measurably moves Reynosa<->McAllen flow
--                         and should be exposed as a separate OLS feature.

CREATE TABLE holiday_calendar (
  id BIGSERIAL PRIMARY KEY,
  tenant_id BIGINT NOT NULL DEFAULT 1,
  holiday_date DATE NOT NULL,
  name VARCHAR(80) NOT NULL,
  country VARCHAR(4) NOT NULL,
  drives_border_traffic BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_holiday_date_name UNIQUE (tenant_id, holiday_date, name),
  CONSTRAINT chk_holiday_country CHECK (country IN ('MX', 'US', 'BOTH'))
);

CREATE INDEX idx_holiday_date ON holiday_calendar (tenant_id, holiday_date);

